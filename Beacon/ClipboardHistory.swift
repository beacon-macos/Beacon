import AppKit
import Observation

@MainActor
@Observable
final class ClipboardHistory {
    nonisolated struct Entry: Codable, Identifiable, Hashable, Sendable {
        let id: UUID
        let text: String
        let date: Date
        let source: Source?
    }

    nonisolated struct Source: Codable, Hashable, Sendable {
        let name: String
        let bundleIdentifier: String?

        static var beacon: Source {
            Source(name: "Beacon", bundleIdentifier: Bundle.main.bundleIdentifier)
        }
    }

    nonisolated static var defaultStorageURL: URL {
        URL.applicationSupportDirectory.appending(path: "Beacon/ClipboardHistory.json")
    }

    static let maximumEntryCount = 100
    static let maximumTextLength = 100_000
    private static let pollInterval: TimeInterval = 0.5
    /// Markers from nspasteboard.org that password managers put on items clipboard managers must not record.
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    ]

    private(set) var entries: [Entry] = []

    var isEnabled: Bool {
        didSet {
            defaults.set(isEnabled, forKey: Keys.isEnabled)
            if isEnabled {
                startMonitoring()
            } else {
                stopMonitoring()
                clear()
            }
        }
    }

    var onChange: (() -> Void)?

    private let pasteboard: NSPasteboard
    private let storageURL: URL
    private let defaults: UserDefaults
    private let frontmostSource: @MainActor () -> Source?
    private var isLoaded = false
    private var lastChangeCount: Int
    private var timer: Timer?
    private var saveTask: Task<Void, Never>?

    init(
        pasteboard: NSPasteboard = .general,
        storageURL: URL = ClipboardHistory.defaultStorageURL,
        defaults: UserDefaults = .standard,
        frontmostSource: @escaping @MainActor () -> Source? = ClipboardHistory.frontmostApplicationSource
    ) {
        self.pasteboard = pasteboard
        self.storageURL = storageURL
        self.defaults = defaults
        self.frontmostSource = frontmostSource
        isEnabled = defaults.object(forKey: Keys.isEnabled) as? Bool ?? true
        lastChangeCount = pasteboard.changeCount
    }

    func start() async {
        await load()
        startMonitoring()
    }

    /// Nothing is recorded or saved before loading, so an early copy cannot overwrite the saved history.
    func load() async {
        guard !isLoaded else { return }
        let storageURL = storageURL
        let savedEntries = await Task.detached(priority: .userInitiated) {
            try? JSONDecoder().decode([Entry].self, from: Data(contentsOf: storageURL))
        }.value
        isLoaded = true
        guard isEnabled, let savedEntries else { return }
        entries = Array(savedEntries.prefix(Self.maximumEntryCount))
        onChange?()
    }

    func checkPasteboard() {
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount
        // Finder puts a copied file's name on the pasteboard as text, which isn't what was copied.
        guard let types = pasteboard.types,
              Self.ignoredTypes.isDisjoint(with: types),
              !types.contains(.fileURL),
              let text = pasteboard.string(forType: .string) else { return }
        record(text, source: frontmostSource())
    }

    func copy(_ text: String, source: Source? = .beacon) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        lastChangeCount = pasteboard.changeCount
        record(text, source: source)
    }

    func remove(_ entry: Entry) {
        entries.removeAll { $0.id == entry.id }
        save()
        onChange?()
    }

    func clear() {
        entries.removeAll()
        save()
        onChange?()
    }

    /// Matches every word anywhere in the text, because fuzzy matching would accept almost any long text.
    func entries(matching query: String) -> [Entry] {
        let words = query.split(whereSeparator: \.isWhitespace)
        guard !words.isEmpty else { return entries }
        return entries.filter { entry in
            words.allSatisfy { entry.text.localizedStandardContains($0) }
        }
    }

    static func preview(of text: String) -> String {
        text.drop(while: \.isWhitespace)
            .prefix(300)
            .split(whereSeparator: \.isWhitespace)
            .joined(separator: " ")
    }

    static func frontmostApplicationSource() -> Source? {
        guard let application = NSWorkspace.shared.frontmostApplication,
              let name = application.localizedName else { return nil }
        return Source(name: name, bundleIdentifier: application.bundleIdentifier)
    }

    private func record(_ text: String, source: Source?) {
        guard isEnabled,
              isLoaded,
              text.utf16.count <= Self.maximumTextLength,
              text.contains(where: { !$0.isWhitespace }),
              entries.first?.text != text else { return }
        entries.removeAll { $0.text == text }
        entries.insert(Entry(id: UUID(), text: text, date: .now, source: source), at: 0)
        if entries.count > Self.maximumEntryCount {
            entries.removeLast(entries.count - Self.maximumEntryCount)
        }
        save()
        onChange?()
    }

    private func startMonitoring() {
        guard isEnabled, isLoaded, timer == nil else { return }
        lastChangeCount = pasteboard.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: Self.pollInterval, repeats: true) { [weak self] _ in
            Task { @MainActor [weak self] in
                self?.checkPasteboard()
            }
        }
        timer?.tolerance = Self.pollInterval / 2
    }

    private func stopMonitoring() {
        timer?.invalidate()
        timer = nil
    }

    private func save() {
        let entries = entries
        let storageURL = storageURL
        let previousSave = saveTask
        saveTask = Task.detached(priority: .utility) {
            await previousSave?.value
            if entries.isEmpty {
                try? FileManager.default.removeItem(at: storageURL)
            } else {
                try? FileManager.default.createDirectory(
                    at: storageURL.deletingLastPathComponent(),
                    withIntermediateDirectories: true
                )
                try? JSONEncoder().encode(entries).write(to: storageURL, options: .atomic)
            }
        }
    }

    private enum Keys {
        static let isEnabled = "clipboardHistoryEnabled"
    }
}
